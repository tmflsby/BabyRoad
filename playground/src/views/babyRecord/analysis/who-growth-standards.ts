/**
 * 取指定性别/指标在某一整月龄处的参照点
 * @param sex 宝宝性别
 * @param indicator 指标（体重或身长）
 * @param month 月龄，超出 0-36 返回 null
 */
export function referencePointAt(
  sex: 'boy' | 'girl',
  indicator: ReferencedIndicator,
  month: number,
): null | PercentilePoint {
  const rounded = Math.round(month);
  if (rounded < 0 || rounded > WHO_MAX_AGE_MONTH) {
    return null;
  }
  return WHO_GROWTH_STANDARDS[sex][indicator][rounded] ?? null;
}

/**
 * 构造参照带序列：逐月输出 `[月龄, 值]` 点
 * @param sex 宝宝性别
 * @param indicator 指标
 * @param percentile 分位（3/50/97）
 */
export function referenceSeries(
  sex: 'boy' | 'girl',
  indicator: ReferencedIndicator,
  percentile: 3 | 50 | 97,
): [number, number][] {
  const points: [number, number][] = [];
  for (let month = 0; month <= WHO_MAX_AGE_MONTH; month += 1) {
    const point = referencePointAt(sex, indicator, month);
    if (point) {
      points.push([month, point[PERCENTILE_INDEX[percentile]]]);
    }
  }
  return points;
}
